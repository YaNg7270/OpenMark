import DOMPurify from 'dompurify';

/**
 * HTML sanitiser for rendered markdown.
 *
 * ## The security model
 *
 * Sanitisation runs on the **intermediate** HTML, before it is inserted into the DOM.
 * At that point every expensive construct is still an empty placeholder: math, Mermaid
 * and code blocks carry no content at all. That ordering is deliberate and is the reason
 * this app can be both permissive and safe:
 *
 *  - Raw HTML in the author's document (`<br>`, `<kbd>`, `<details>`, …) is sanitised,
 *    so `<script>`, event handlers and `javascript:` URLs never survive.
 *  - MathJax and Mermaid then inject their own SVG into containers that were already
 *    sanitised. Their output is generated by trusted libraries, not by the document, and
 *    Mermaid additionally runs with `securityLevel: 'strict'` and `htmlLabels: false`.
 *
 * The alternative — sanitising *after* typesetting — is what forces other editors into
 * the awkward position of having to allow `<use>` and `foreignObject`, which is exactly
 * the surface DOMPurify's SVG rules exist to block.
 */

/** Tags that markdown, GFM and our own pipeline legitimately produce. */
const ALLOWED_TAGS = [
  // markdown / GFM
  'a', 'abbr', 'blockquote', 'br', 'code', 'dd', 'del', 'details', 'div', 'dl', 'dt', 'em',
  'figcaption', 'figure', 'h1', 'h2', 'h3', 'h4', 'h5', 'h6', 'hr', 'img', 'input', 'ins',
  'kbd', 'li', 'mark', 'ol', 'p', 'pre', 's', 'samp', 'section', 'small', 'span', 'strong',
  'sub', 'summary', 'sup', 'table', 'tbody', 'td', 'tfoot', 'th', 'thead', 'tr', 'u', 'ul', 'var',
  // footnote back-references and task lists
  'label',
  // our placeholders
  'mjx-container',
];

const ALLOWED_ATTR = [
  'align', 'alt', 'aria-hidden', 'aria-label', 'checked', 'class', 'colspan', 'data-*', 'dir',
  'disabled', 'height', 'href', 'id', 'lang', 'loading', 'open', 'rel', 'role', 'rowspan',
  'scope', 'src', 'start', 'style', 'title', 'type', 'value', 'width',
];

export interface SanitizeResult {
  html: string;
  /** Lower-cased tag names that were removed, deduplicated. */
  removed: string[];
}

/**
 * URL schemes permitted in attributes.
 *
 * This is DOMPurify's default pattern with `asset` added — the scheme the Tauri webview uses
 * to serve local files, and therefore how every relative image in a document is loaded.
 *
 * **Do not replace this with a simple anchored scheme list.** A pattern like
 * `/^(?:https?|mailto):/` looks safer but is far more destructive: DOMPurify applies
 * `ALLOWED_URI_REGEXP` to *every* URI-valued attribute, including ones with non-URL values,
 * and the `|[^a-z]|[a-z+.\-]+(?:[^a-z+.\-:]|$)` alternative below is what permits relative
 * URLs. Removing it silently deletes `href="./next.md"`, `src="img/fig-1.png"`, `href="#top"`
 * and even `type="checkbox"` — a defect that renders as a document with no images and no
 * working links. `tests/unit/dom/sanitize.test.ts` pins every one of those cases.
 */
const ALLOWED_URI_REGEXP = /^(?:(?:(?:f|ht)tps?|mailto|tel|asset):|[^a-z]|[a-z+.\-]+(?:[^a-z+.\-:]|$))/i;

/**
 * Removes anything executable from rendered markdown HTML.
 *
 * `FORBID_TAGS`/`FORBID_ATTR` are belt-and-braces on top of the allow-list: they make the
 * intent explicit and keep behaviour stable if the allow-list is extended later.
 *
 * **`KEEP_CONTENT` must not be set to `false`.** Setting it deletes *every* text node in the
 * document, not just the contents of removed elements, which silently empties the whole
 * page while leaving the element structure intact — a failure mode that looks like a CSS
 * bug. Verified against DOMPurify 3.4.17; pinned in the same test file. The default (`true`)
 * is already safe here: `script`, `style`, `iframe` and friends are in DOMPurify's
 * forbids-contents list, so their bodies are discarded regardless.
 */
export function sanitizeHtml(html: string): SanitizeResult {
  const removed = new Set<string>();
  const clean = DOMPurify.sanitize(html, {
    ALLOWED_TAGS,
    ALLOWED_ATTR,
    ALLOWED_URI_REGEXP,
    FORBID_TAGS: ['script', 'style', 'iframe', 'object', 'embed', 'form', 'base', 'link', 'meta'],
    FORBID_ATTR: ['onerror', 'onload', 'onclick', 'onmouseover', 'onfocus', 'formaction', 'srcdoc'],
    // Keep the DOM shape stable so the placeholder lookups still resolve.
    RETURN_DOM: false,
    RETURN_DOM_FRAGMENT: false,
    // Never switch parser: the XHTML parser changes handling of foreign content.
    SAFE_FOR_XML: true,
    // Report rather than delete silently, so the diagnostics panel can explain what went.
    ADD_ATTR: ['target'],
    ALLOW_DATA_ATTR: true,
    ALLOW_ARIA_ATTR: true,
  });

  // Diff the input against the output to name what was stripped. DOMPurify's own
  // `removed` callbacks cover elements, not attributes, so we scan the source for the
  // tags we explicitly forbid — cheap and precise enough for a user-facing message.
  for (const tag of ['script', 'iframe', 'object', 'embed', 'form', 'style', 'link', 'meta', 'base']) {
    if (new RegExp(`<\\s*${tag}[\\s>]`, 'i').test(html)) removed.add(tag);
  }
  if (/\son[a-z]+\s*=/i.test(html)) removed.add('event-handler');

  return { html: String(clean), removed: [...removed] };
}
